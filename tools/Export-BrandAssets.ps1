# Regenerate all logo variants from the single SVG source. Run with PowerShell on Windows.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, WindowsBase
$brandRoot = Split-Path -Parent $PSScriptRoot
$assetDirectory = Join-Path $brandRoot 'desktop/PersonGuard.Desktop/Assets'
$svgPath = Join-Path $assetDirectory 'Logo.svg'
[xml]$svg = Get-Content -LiteralPath $svgPath -Raw
$path = $svg.DocumentElement.SelectSingleNode("*[local-name()='path']")
$geometry = [System.Windows.Media.Geometry]::Parse('F0 ' + $path.d)
$brush = [System.Windows.Media.BrushConverter]::new().ConvertFromString($path.fill)
$drawing = [System.Windows.Media.GeometryDrawing]::new($brush, $null, $geometry)

# A transparent 64 x 64 drawing keeps the same optical margins in WPF and SVG.
$xaml = @"
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <!-- Generated by tools/Export-BrandAssets.ps1 from Assets/Logo.svg. -->
  <!-- Load the full-size PNG: BitmapImage selects only the first 16px ICO frame. -->
  <BitmapImage x:Key="BrandIcon" UriSource="Logo.png" />
  <DrawingImage x:Key="BrandLogo">
    <DrawingImage.Drawing>
      <DrawingGroup>
        <GeometryDrawing Brush="Transparent" Geometry="M0 0H64V64H0Z" />
        <GeometryDrawing Brush="$($path.fill)" Geometry="F0 $($path.d)" />
      </DrawingGroup>
    </DrawingImage.Drawing>
  </DrawingImage>
</ResourceDictionary>
"@
[IO.File]::WriteAllText((Join-Path $assetDirectory 'Logo.xaml'), $xaml)

$sizes = @(16, 20, 24, 32, 40, 48, 64, 128, 256)
# Fill the shell icon with a 2px margin on the 64px canvas; keep in-app SVG margins.
$iconScale = 60.0 / [Math]::Max($geometry.Bounds.Width, $geometry.Bounds.Height)
$iconTransform = [System.Windows.Media.Matrix]::new($iconScale, 0, 0, $iconScale,
    32 - ($geometry.Bounds.X + $geometry.Bounds.Width / 2) * $iconScale,
    32 - ($geometry.Bounds.Y + $geometry.Bounds.Height / 2) * $iconScale)
$images = foreach ($size in $sizes) {
    $visual = [System.Windows.Media.DrawingVisual]::new()
    $context = $visual.RenderOpen()
    $context.PushTransform([System.Windows.Media.ScaleTransform]::new($size / 64.0, $size / 64.0))
    $context.PushTransform([System.Windows.Media.MatrixTransform]::new($iconTransform))
    $context.DrawDrawing($drawing)
    $context.Pop()
    $context.Pop()
    $context.Close()
    $bitmap = [System.Windows.Media.Imaging.RenderTargetBitmap]::new($size, $size, 96, 96, [System.Windows.Media.PixelFormats]::Pbgra32)
    $bitmap.Render($visual)
    $encoder = [System.Windows.Media.Imaging.PngBitmapEncoder]::new()
    $encoder.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
    $stream = [IO.MemoryStream]::new()
    $encoder.Save($stream)
    $bytes = $stream.ToArray()
    $stream.Dispose()
    if ($size -eq 256) { [IO.File]::WriteAllBytes((Join-Path $assetDirectory 'Logo.png'), $bytes) }
    [pscustomobject]@{ Size = $size; Bytes = $bytes }
}

# Windows ICO directory with PNG frames for every common taskbar/DPI size.
$iconStream = [IO.File]::Create((Join-Path $assetDirectory 'PersonGuard.ico'))
$writer = [IO.BinaryWriter]::new($iconStream)
try {
    $writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$images.Count)
    $offset = 6 + 16 * $images.Count
    foreach ($entry in $images) {
        $dimension = if ($entry.Size -eq 256) { 0 } else { $entry.Size }
        $writer.Write([byte]$dimension); $writer.Write([byte]$dimension)
        $writer.Write([byte]0); $writer.Write([byte]0)
        $writer.Write([uint16]1); $writer.Write([uint16]32)
        $writer.Write([uint32]$entry.Bytes.Length); $writer.Write([uint32]$offset)
        $offset += $entry.Bytes.Length
    }
    foreach ($entry in $images) { $writer.Write([byte[]]$entry.Bytes) }
}
finally { $writer.Dispose() }
Write-Host 'Exported WPF, SVG, PNG and Windows ICO logo assets.'
